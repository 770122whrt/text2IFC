export const STORAGE_KEY='text2ifc.ui.language';
function browserStorage(){try{return globalThis.localStorage;}catch{return undefined;}}
export function readLanguage(storage=browserStorage()){try{return storage?.getItem(STORAGE_KEY)==='en'?'en':'zh';}catch{return 'zh';}}
let language=readLanguage();const listeners=new Set(),boundValues=new WeakMap();
export const getLanguage=()=>language;
export function t(key,values={},locale=language){
 const template=catalogs[locale]?.[key];if(template===undefined)return '['+key+']';
 return template.replace(/\{(\w+)\}/g,(match,name)=>Object.hasOwn(values,name)?String(values[name]):match);
}
export function bindText(node,key,values={}){if(!node)return;node.dataset.i18n=key;boundValues.set(node,values);node.textContent=t(key,values);}
export function applyTranslations(root=globalThis.document){
 if(!root?.querySelectorAll)return;
 for(const node of root.querySelectorAll('[data-i18n]'))node.textContent=t(node.dataset.i18n,boundValues.get(node)||{});
 for(const attr of ['title','aria-label','placeholder'])for(const node of root.querySelectorAll('[data-i18n-'+attr+']'))node.setAttribute(attr,t(node.getAttribute('data-i18n-'+attr)));
 if(root.documentElement)root.documentElement.lang=language==='zh'?'zh-CN':'en';
}
export function setLanguage(value,{persist=true,storage=browserStorage()}={}){
 if(value!=='zh'&&value!=='en')return false;
 if(persist)try{storage?.setItem(STORAGE_KEY,value);}catch{/* Storage is optional, switching is not. */}
 if(value===language)return false;language=value;applyTranslations();for(const callback of listeners)callback(value);return true;
}
export function onLanguageChange(callback){listeners.add(callback);return ()=>listeners.delete(callback);}
export function uiError(key,values={}){const error=new Error(t(key,values));error.i18nKey=key;error.i18nValues=values;return error;}
